package com.hutka.backend.weather.enums;

/**
 * Неблагоприятное условие для поездки (раздел 12). ТЗ называет четыре: дождь, гололёд, туман, сильный ветер —
 * snow и thunderstorm добавлены сверх списка (WEATHER_DECISIONS.md, п. 4). Правила отнесения погоды к условию —
 * в WeatherRules. Клиент строит текст предупреждения по этому значению (сервер текст не формирует).
 */
public enum WeatherHazard {
    /** Дождь умеренной силы и сильнее, включая ливни. */
    rain,
    /** Гололёд: замерзающие морось и дождь (черноледицу без осадков прогноз не показывает). */
    ice,
    /** Туман или видимость ниже порога. */
    fog,
    /** Порывы ветра выше порога. */
    strong_wind,
    /** Снегопад умеренной силы и сильнее, включая снежные заряды. */
    snow,
    /** Гроза. */
    thunderstorm
}
